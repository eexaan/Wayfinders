"""
================================================================================
Schedule cross-check: MTCC published timetable vs the official RTL feed
================================================================================
Maldives Datathon 2026 | Team Wayfinders  |  Dev B task 2c (SPEC §10 "must")

WHAT THIS PROVES
    That the supply side is right. Every capacity number in this project comes
    from the RTL 2026 feed. If that feed implies a service level the operator
    never published, then every load factor downstream is wrong. This checks
    the feed against MTCC's own published schedule PDFs.

WHY IT IS A COHERENCE CHECK AND NOT AN EQUALITY CHECK
    The two sources are 18 months apart and describe different things:
        RTL feed        2026-10-24, an actual list of trip departure times
        MTCC PDFs       published March 2025, a FREQUENCY BAND table
                        ("0600 - 1030 ... 30 MINUTES"), not a trip list
    So the PDFs give a service *level* and the feed gives actual *trips*. They
    should agree closely. They cannot be identical, and three mechanisms are
    reported rather than assumed away:

        1. Service revisions between March 2025 and October 2026.
        2. Band vs trip-list rounding. A band running 07:20-14:00 at 20 min
           yields 21 trips; a real timetable would not space them perfectly.
        3. The service-day boundary. Bands that continue past midnight (R13
           runs 06:00-02:30 at 10 min) create trips after 00:00 which may be
           counted against the next service day by the API, and vice versa.

HOW THE BANDS ARE TURNED INTO TRIPS
    For a band (start, end, headway):  trips = floor(span / headway) + 1
    with span = end - start, or end + 24h - start when the band crosses
    midnight. Departures are generated by stepping from `start`, so they can be
    bucketed by clock hour and compared to the feed hour by hour.

THE STRONGER OF THE TWO TESTS
    Daily totals are deliberately reported second. The primary test is
    hour-by-hour inside the captured window (11:00-23:59), because that is the
    only place the two sources describe the same clock hours. A route can match
    on a daily total while being wrong by hours, and that would silently corrupt
    every peak load factor.

OUTPUTS
    dashboard/data/schedule_crosscheck.csv          route x day-type vs feed
    dashboard/data/schedule_crosscheck_hourly.csv   route x hour, PDF vs feed
    dashboard/data/schedule_crosscheck_flags.csv    parse anomalies, for audit
"""

from __future__ import annotations

import pathlib
import re
import subprocess

import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "dashboard" / "data"

ROUTES = [f"R{i}" for i in range(1, 15)]
CAPTURED_HOURS = range(11, 24)

# The PDFs are the "Ramadan 1446" edition (February-March 2025), which is why
# they are no longer the supply source at all -- see RESEARCH.md 2.4a and 8.
# That matters for how this file is read: the PDFs describe a *Ramadan* service,
# the feed describes a regular October day, so a systematic divergence is
# expected and is not evidence that either is wrong.
PDF_VINTAGE = "Ramadan 1446 (Feb-Mar 2025)"

# Tolerance on the hourly test. One trip per hour is roughly a third of a
# 20-30 minute headway; beyond that the two documents describe different
# services rather than the same one rounded differently.
HOURLY_MAE_TOLERANCE = 1.0

# One en-dash, one hyphen and one em-dash all appear in these PDFs. Missing one
# silently drops bands, which is exactly the class of error this file exists to
# catch, so all three are matched explicitly.
BAND_RE = re.compile(r"(\d{3,4})\s*[-\u2013\u2014]\s*(\d{2}:?\d{2})\s+(\d{1,3})\s*MIN", re.I)
FRIDAY_RE = re.compile(r"^FRIDAY$", re.I)
SAT_HOL_RE = re.compile(r"^SATURDAY\s*&\s*PUBLIC\s*HOLIDAYS", re.I)
SUNDAY_RE = re.compile(r"^SUNDAY", re.I)


def to_min(s: str) -> int:
    """'0630' or '06:30' or '6:30' -> minutes after midnight."""
    s = s.replace(":", "").strip()
    if len(s) == 3:
        s = "0" + s
    return int(s[:2]) * 60 + int(s[2:])


def parse_pdf(code: str) -> tuple[dict, list[str]]:
    """Return {day_type: [(start_min, end_min, headway_min)]} plus anomalies."""
    txt = subprocess.run(
        ["pdftotext", "-layout", str(RAW / f"{code}.pdf"), "-"],
        capture_output=True, text=True, check=True,
    ).stdout

    blocks: dict[str, list[tuple[int, int, int]]] = {}
    anomalies: list[str] = []
    current = None

    for line in txt.splitlines():
        stripped = line.strip()
        upper = stripped.upper()

        if FRIDAY_RE.match(upper):
            current = "friday"
            blocks.setdefault(current, [])
            continue
        if SAT_HOL_RE.match(upper):
            current = "saturday_holiday"
            blocks.setdefault(current, [])
            continue
        if SUNDAY_RE.match(upper):
            # "SUNDAY..SATURDAY" includes Saturday; "SUNDAY..THURSDAY" does not.
            current = "sat_in_weekday_block" if "SATURDAY" in upper else "weekday"
            blocks.setdefault(current, [])
            continue

        m = BAND_RE.search(line)
        if m:
            if current is None:
                anomalies.append(f"band before any day header: {stripped[:60]}")
                continue
            a, b, headway = to_min(m.group(1)), to_min(m.group(2)), int(m.group(3))
            if headway <= 0:
                anomalies.append(f"non-positive headway: {stripped[:60]}")
                continue
            if b <= a:
                # crosses midnight; keep both numbers, resolve in expansion
                b += 1440
            if b - a > 30 * 60:
                anomalies.append(f"band longer than 30h: {stripped[:60]}")
            blocks[current].append((a, b, headway))

    if not blocks:
        anomalies.append("no timetable blocks found")
    return blocks, anomalies


def expand(bands: list[tuple[int, int, int]]) -> list[int]:
    """Departure minutes for a set of bands, with midnight unwrapped to >1440."""
    trips: list[int] = []
    for start, end, headway in bands:
        t = start
        while t <= end:
            trips.append(t)
            t += headway
    return trips


def saturday_bands(blocks: dict) -> tuple[list[tuple[int, int, int]], str]:
    """The block that governs a Saturday service, and its name.

    Preference order matters. If a route publishes a separate Saturday &
    Public Holidays table, that overrides a Sunday..Saturday table, because the
    operator clearly distinguishes the two. Getting this backwards would compare
    a weekday service against a Saturday.
    """
    for key in ("saturday_holiday", "sat_in_weekday_block", "weekday"):
        if key in blocks and blocks[key]:
            return blocks[key], key
    return [], "none"


def main() -> None:
    feed_master = pd.read_csv(OUT / "routes_master.csv").set_index("route_code")
    feed_hourly = pd.read_csv(OUT / "route_service_by_hour.csv")

    daily_rows, hourly_rows, flag_rows = [], [], []

    for code in ROUTES:
        blocks, anomalies = parse_pdf(code)
        bands, which = saturday_bands(blocks)
        for a in anomalies:
            flag_rows.append({"route_code": code, "issue": a})

        pdf_trips = expand(bands)
        pdf_daily = len(pdf_trips)
        feed_daily = (
            float(feed_master.loc[code, "trips_per_day"])
            if code in feed_master.index and pd.notna(feed_master.loc[code, "trips_per_day"])
            else np.nan
        )

        # Per-hour comparison on the same clock hours as the capture.
        pdf_hour = pd.Series(0, index=range(24), dtype=int)
        for t in pdf_trips:
            pdf_hour[(t // 60) % 24] += 1

        fh = feed_hourly[feed_hourly["route_code"] == code].set_index("hour")
        common = [h for h in CAPTURED_HOURS if h in fh.index and bool(fh.loc[h, "captured"])]

        diffs = []
        for h in common:
            f = int(fh.loc[h, "departures"])
            hourly_rows.append({
                "route_code": code,
                "hour": h,
                "pdf_departures": int(pdf_hour[h]),
                "feed_departures": f,
                "diff": f - int(pdf_hour[h]),
            })
            diffs.append(f - int(pdf_hour[h]))

        pdf_window = int(pdf_hour[list(common)].sum()) if common else 0
        feed_window = int(sum(int(fh.loc[h, "departures"]) for h in common)) if common else 0

        pct = (feed_daily - pdf_daily) / pdf_daily * 100 if (feed_daily == feed_daily and pdf_daily) else np.nan
        mae = round(float(np.mean(np.abs(diffs))), 2) if diffs else None

        # The verdict is based on the HOURLY test, not the daily one. The daily
        # total mixes in the Ramadan-vs-regular difference and the service-day
        # boundary, so it cannot distinguish "the feed is wrong" from "the
        # documents describe different seasons". The hourly test compares the
        # same clock hours on a comparable basis and is therefore the one that
        # can actually fail on a real defect.
        if mae is None:
            verdict = "NO_FEED_DATA"
            note = "feed returns no timings for this route, so nothing to compare"
        elif mae <= HOURLY_MAE_TOLERANCE:
            verdict = "PASS"
            note = "feed and published schedule agree hour by hour in the captured window"
        else:
            verdict = "REVIEW"
            note = "feed runs materially more or less service than published, hour by hour"

        # A band crossing midnight creates trips after 00:00 that the API may
        # count against the next service day. Reported so the daily gap can be
        # attributed rather than guessed at.
        after_midnight = sum(1 for t in pdf_trips if t >= 1440)

        daily_rows.append({
            "route_code": code,
            "pdf_block_used": which,
            "pdf_bands": len(bands),
            "pdf_vintage": PDF_VINTAGE,
            "pdf_trips_per_day": pdf_daily,
            "pdf_trips_after_midnight": after_midnight,
            "feed_trips_per_day": feed_daily if feed_daily == feed_daily else None,
            "diff_trips": (feed_daily - pdf_daily) if feed_daily == feed_daily else None,
            "diff_pct": round(float(pct), 1) if pct == pct else None,
            "pdf_trips_in_captured_window": pdf_window,
            "feed_trips_in_captured_window": feed_window,
            "hourly_mae_captured": mae,
            "hourly_max_abs_diff": int(np.max(np.abs(diffs))) if diffs else None,
            "verdict": verdict,
            "note": note,
        })

    daily = pd.DataFrame(daily_rows)
    hourly = pd.DataFrame(hourly_rows)
    # Keep the columns even when nothing is wrong, so the file stays parseable
    # and a downstream reader can distinguish "clean" from "missing".
    flags = pd.DataFrame(flag_rows, columns=["route_code", "issue"])

    daily.to_csv(OUT / "schedule_crosscheck.csv", index=False)
    hourly.to_csv(OUT / "schedule_crosscheck_hourly.csv", index=False)
    flags.to_csv(OUT / "schedule_crosscheck_flags.csv", index=False)

    pd.set_option("display.width", 240)
    print("=" * 120)
    print("SCHEDULE CROSS-CHECK — MTCC published bands (Mar 2025) vs official RTL feed (Oct 2026)")
    print("=" * 120)
    print(daily.to_string(index=False))
    print()
    checked = daily[daily["verdict"].isin(["PASS", "REVIEW"])]
    print(f"routes with an hourly comparison : {len(checked)} of {len(daily)}")
    if len(checked):
        print(f"  PASS (MAE <= {HOURLY_MAE_TOLERANCE} trip/h)     : {(checked['verdict'] == 'PASS').sum()}")
        print(f"  REVIEW                        : {(checked['verdict'] == 'REVIEW').sum()}")
        print(f"  median hourly MAE (11-23h)    : {checked['hourly_mae_captured'].median():.2f} trips/hour")
        print(f"  worst hourly MAE              : {checked['hourly_mae_captured'].max():.2f} trips/hour")
        print()
        print(f"  daily diff is CONFOUNDED by the {PDF_VINTAGE} vintage and the")
        print(f"  service-day boundary, so it is reported but not used as the verdict:")
        print(f"    median |daily diff|         : {checked['diff_pct'].abs().median():.1f}%")
        print(f"    range                       : {checked['diff_pct'].min():+.1f}% to {checked['diff_pct'].max():+.1f}%")
    print()
    if len(flags):
        print("PARSE ANOMALIES (audit, not necessarily errors):")
        print(flags.to_string(index=False))
    print()
    print(f"wrote {OUT/'schedule_crosscheck.csv'}         ({len(daily)} rows)")
    print(f"wrote {OUT/'schedule_crosscheck_hourly.csv'}  ({len(hourly)} rows)")
    print(f"wrote {OUT/'schedule_crosscheck_flags.csv'}   ({len(flags)} rows)")


if __name__ == "__main__":
    main()
